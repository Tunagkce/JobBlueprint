-- Also cover legacy databases that predate app_account but were already
-- non-empty when Flyway was introduced and therefore baseline at version 1.
CREATE TABLE IF NOT EXISTS app_account (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(320) NOT NULL UNIQUE,
    password_hash VARCHAR(100) NOT NULL
);

-- Hibernate may already have created this table in a pre-Flyway local database.
-- Preserve it and add the ownership/schema fields Flyway now manages.
CREATE TABLE IF NOT EXISTS account_profile (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) UNIQUE,
    full_name VARCHAR(160),
    email VARCHAR(320),
    phone VARCHAR(80),
    phone_country_code VARCHAR(8),
    phone_country_iso VARCHAR(2),
    city VARCHAR(120),
    country VARCHAR(120),
    linked_in_url VARCHAR(500),
    portfolio_url VARCHAR(500),
    professional_summary VARCHAR(5000)
);

