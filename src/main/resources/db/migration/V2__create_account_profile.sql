-- If an old profile table exists, assign it only when ownership is unambiguous.
-- Otherwise retain the data under an inaccessible legacy key instead of exposing
-- it to an arbitrary account.
DO $$
DECLARE
    local_account_count INTEGER;
    local_account_id BIGINT;
BEGIN
    SELECT COUNT(*), MIN(id) INTO local_account_count, local_account_id
    FROM app_account;

    IF local_account_count = 1 THEN
        UPDATE account_profile
        SET owner_key = 'local:' || local_account_id::text
        WHERE owner_key IS NULL AND id = 1;
    END IF;

    UPDATE account_profile
    SET owner_key = 'legacy:unassigned:' || id::text
    WHERE owner_key IS NULL;
END $$;

CREATE UNIQUE INDEX IF NOT EXISTS account_profile_owner_key_uq
    ON account_profile (owner_key);
ALTER TABLE account_profile ALTER COLUMN owner_key SET NOT NULL;

-- Keep the existing single-user profile when there is exactly one local account.
-- If there are multiple accounts, leave the legacy row untouched rather than
-- guessing who owns personal data.
DO $$
DECLARE
    local_account_count INTEGER;
    local_account_id BIGINT;
BEGIN
    IF to_regclass('public.user_profile') IS NOT NULL
       AND to_regclass('public.app_account') IS NOT NULL THEN
        EXECUTE 'SELECT COUNT(*), MIN(id) FROM public.app_account'
            INTO local_account_count, local_account_id;

        IF local_account_count = 1 THEN
            EXECUTE $copy$
                INSERT INTO public.account_profile (
                    owner_key, full_name, email, phone, phone_country_code,
                    phone_country_iso, city, country, linked_in_url,
                    portfolio_url, professional_summary
                )
                SELECT 'local:' || account.id::text, profile.full_name,
                    profile.email, profile.phone, profile.phone_country_code,
                    profile.phone_country_iso, profile.city, profile.country,
                    profile.linked_in_url, profile.portfolio_url,
                    profile.professional_summary
                FROM public.user_profile profile
                CROSS JOIN public.app_account account
                WHERE profile.id = 1 AND account.id = $1
                ON CONFLICT (owner_key) DO NOTHING
            $copy$ USING local_account_id;
        END IF;
    END IF;
END $$;
