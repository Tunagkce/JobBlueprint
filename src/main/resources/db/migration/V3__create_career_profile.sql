-- Career profile: the verified facts that resume tailoring and form filling
-- draw from. Every row is owned by one signed-in identity (owner_key, the same
-- key account_profile uses) and is only ever read/written filtered by it.

CREATE TABLE work_experience (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) NOT NULL,
    company VARCHAR(200) NOT NULL,
    title VARCHAR(200) NOT NULL,
    location VARCHAR(200),
    employment_type VARCHAR(30),
    start_date DATE NOT NULL,
    end_date DATE,
    is_current BOOLEAN NOT NULL DEFAULT FALSE,
    description VARCHAR(5000),
    CONSTRAINT work_experience_dates_ck CHECK (end_date IS NULL OR end_date >= start_date),
    CONSTRAINT work_experience_current_ck CHECK (NOT is_current OR end_date IS NULL)
);
CREATE INDEX work_experience_owner_idx ON work_experience (owner_key);

CREATE TABLE education (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) NOT NULL,
    institution VARCHAR(200) NOT NULL,
    degree VARCHAR(200),
    field_of_study VARCHAR(200),
    start_date DATE,
    end_date DATE,
    grade VARCHAR(50),
    description VARCHAR(2000),
    CONSTRAINT education_dates_ck CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date)
);
CREATE INDEX education_owner_idx ON education (owner_key);

CREATE TABLE skill (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) NOT NULL,
    name VARCHAR(100) NOT NULL,
    level VARCHAR(20)
);
CREATE UNIQUE INDEX skill_owner_name_uq ON skill (owner_key, lower(name));

CREATE TABLE spoken_language (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) NOT NULL,
    language VARCHAR(80) NOT NULL,
    proficiency VARCHAR(20) NOT NULL
);
CREATE UNIQUE INDEX spoken_language_owner_language_uq ON spoken_language (owner_key, lower(language));

-- Standard answers most application forms ask for (one row per owner).
CREATE TABLE application_preferences (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_key VARCHAR(512) NOT NULL UNIQUE,
    desired_titles VARCHAR(1000),
    preferred_work_mode VARCHAR(20),
    willing_to_relocate BOOLEAN,
    work_authorization VARCHAR(500),
    requires_sponsorship BOOLEAN,
    notice_period_days INTEGER CHECK (notice_period_days IS NULL OR notice_period_days BETWEEN 0 AND 365),
    available_from DATE,
    salary_min INTEGER CHECK (salary_min IS NULL OR salary_min >= 0),
    salary_max INTEGER CHECK (salary_max IS NULL OR salary_max >= 0),
    salary_currency VARCHAR(3),
    military_service_status VARCHAR(30),
    driving_license VARCHAR(50),
    CONSTRAINT application_preferences_salary_ck CHECK (salary_min IS NULL OR salary_max IS NULL OR salary_max >= salary_min)
);
